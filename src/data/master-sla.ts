// ─── HELPER: AUTOMATIC COMPLIANCE EVALUATION ENGINE ──────────────────
export function evaluateCompliance(targetStr: string, actualStr: string | undefined): SLAComplianceStatus {
  if (!actualStr || actualStr.trim() === '' || actualStr.toLowerCase() === 'pending' || actualStr === '-') {
    return 'Pending / Not Measured';
  }

  const cleanTarget = targetStr.trim();
  const cleanActual = actualStr.trim();

  // Case 1: Target contains '<' (e.g. '<2%', '< 5%', '<10%', '< 4 Hours', '< 2 Hours')
  if (cleanTarget.startsWith('<')) {
    const numTargetMatch = cleanTarget.replace(/[^\d.]/g, '');
    const numActualMatch = cleanActual.replace(/[^\d.]/g, '');
    if (numTargetMatch && numActualMatch) {
      const targetVal = parseFloat(numTargetMatch);
      const actualVal = parseFloat(numActualMatch);
      if (!isNaN(targetVal) && !isNaN(actualVal)) {
        return actualVal <= targetVal ? 'Met' : 'Not Met';
      }
    }
  }

  // Case 2: Percentage target (e.g. '100.00%', '98.00%', '95%', '99.90%')
  if (cleanTarget.includes('%')) {
    const targetVal = parseFloat(cleanTarget.replace('%', ''));
    const actualVal = parseFloat(cleanActual.replace('%', ''));
    if (!isNaN(targetVal) && !isNaN(actualVal)) {
      return actualVal >= targetVal ? 'Met' : 'Not Met';
    }
  }

  // Case 3: Pure number count target (e.g. '4', '10', '2', '3')
  const numTarget = parseFloat(cleanTarget);
  const numActual = parseFloat(cleanActual);
  if (!isNaN(numTarget) && !isNaN(numActual)) {
    return numActual >= numTarget ? 'Met' : 'Not Met';
  }

  // Case 4: Yes / No / Done / Approved string matching
  const lowerActual = cleanActual.toLowerCase();
  if (lowerActual.includes('yes') || lowerActual.includes('met') || lowerActual.includes('approved') || lowerActual.includes('achieved') || lowerActual.includes('100%')) {
    return 'Met';
  }
  if (lowerActual.includes('no') || lowerActual.includes('failed') || lowerActual.includes('rejected')) {
    return 'Not Met';
  }

  return 'Pending / Not Measured';
}

