// ─── DERIVED STATISTICS ───────────────────────────────────
export const getTechStats = () => {
  const platforms = technologyPlatforms;
  return {
    total: platforms.length,
    healthy: platforms.filter((p) => p.health === 'healthy').length,
    atRisk: platforms.filter((p) => p.health === 'at-risk' || p.health === 'attention').length,
    critical: platforms.filter((p) => p.health === 'critical').length,
    totalExceptions: platforms.reduce((sum, p) => sum + p.openExceptions, 0),
    totalAlerts: platforms.reduce((sum, p) => sum + p.criticalAlerts, 0),
  };
};
