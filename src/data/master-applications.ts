export interface ApplicationRecord {
  id: string;
  name: string;
  businessService: string;
  businessDomain: string;
  criticality: 'Critical' | 'High' | 'Medium' | 'Low';
  environment: 'Production' | 'Staging' | 'Development';
  availability: string;
  availabilityVal: number;
  performanceState: 'Normal' | 'Degraded' | 'Critical';
  activeIncidentsCount: number;
  health: 'Healthy' | 'Degraded' | 'Critical' | 'Maintenance';
  businessOwner: string;
  itOwner: string;
  supportTeam: string;
  vendor: string;
  technologyStack: string;
  version: string;
  hosting: 'On-Premises' | 'GCP Cloud' | 'Azure Cloud' | 'Hybrid';
  lifecycle: 'Active' | 'Under Transformation' | 'Due for Review' | 'Phasing Out';
  lastReview: string;
  nextReview: string;
  responseTimeSec: number;
  thresholdSec: number;
  errorRatePct: number;
  transactionsPerHr: number;
  coverageType: '24x7' | 'Business Hours';
  l1Support: string;
  l2Support: string;
  l3Support: string;
  onCallAvailable: boolean;
  vendorSupport: boolean;
  activeIncidentId?: string;
  activeProblemId?: string;
  activeChangeId?: string;
}

export interface BusinessServiceRecord {
  id: string;
  name: string;
  criticality: 'Critical' | 'High' | 'Medium' | 'Low';
  supportingAppsCount: number;
  availability: string;
  currentState: 'Healthy' | 'Degraded' | 'Critical';
  description: string;
  owner: string;
  downstreamImpact: string;
  dependencyChain: string[];
}

export interface AppIncidentRecord {
  incidentNumber: string;
  appId: string;
  appName: string;
  businessService: string;
  priority: 'P1' | 'P2' | 'P3' | 'P4';
  impact: string;
  urgency: string;
  description: string;
  currentStatus: 'Major Incident' | 'In Progress' | 'Monitoring' | 'Resolved';
  assignmentGroup: string;
  assignedEngineer: string;
  openedDate: string;
  age: string;
  businessImpact: string;
  relatedChange?: string;
  relatedProblem?: string;
  servicenowRef: string;
}

export interface AppProblemRecord {
  problemNumber: string;
  appId: string;
  appName: string;
  issue: string;
  relatedIncidents: string;
  rootCause: string;
  rcaStatus: 'RCA In Progress' | 'RCA Completed';
  correctiveAction: string;
  preventiveAction: string;
  owner: string;
  targetClosure: string;
  servicenowRef: string;
}

export interface AppChangeRecord {
  changeNumber: string;
  appId: string;
  appName: string;
  changeType: 'Normal' | 'Standard' | 'Emergency';
  description: string;
  scheduledDate: string;
  risk: 'High' | 'Medium' | 'Low';
  status: 'Scheduled' | 'CAB Approved' | 'Planned' | 'Completed' | 'In Progress';
  releaseVersion: string;
  owner: string;
  servicenowRef: string;
  /** Tower the change applies to (derived from linked application) */
  tower: string;
  /** Person who requested the change */
  requestor: string;
  /** Priority classification */
  priority: 'P1' | 'P2' | 'P3' | 'P4';
  /** Approval workflow status */
  approvalStatus: 'Approved' | 'Pending' | 'Rejected' | 'CAB Review';
  /** Backout plan summary */
  backoutPlan: string;
}

export interface AppDependencyRecord {
  id: string;
  appName: string;
  dependencyName: string;
  dependencyType: 'API' | 'Database' | 'Authentication' | 'Network' | 'External Vendor';
  health: 'Healthy' | 'Degraded' | 'Critical';
  businessImpact: string;
  owner: string;
  lastValidated: string;
}

